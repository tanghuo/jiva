import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,mkdir} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {createServer,chromium} from '../helpers/authenticatedServer.js';
import {resolveBrowserPath} from '../resolveBrowserPath.js';
const browserPath=resolveBrowserPath();
test('fixed Jiva demo leads with six modules, links curated paths to source, and keeps Git secondary',{timeout:90000,skip:!browserPath&&'Browser required'},async t=>{
  const runtime=await mkdtemp(path.join(os.tmpdir(),'jiva-guide-ui-'));
  const app=await createServer({port:0,dataDir:runtime});
  const browser=await chromium.launch({executablePath:browserPath,headless:true});
  t.after(async()=>{await browser.close();await app.close();assert.ok(path.basename(runtime).startsWith('jiva-guide-ui-'));await rm(runtime,{recursive:true,force:true,maxRetries:3});});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(app.url+'#code-projects');
  await page.locator('.jiva-workspace').waitFor({timeout:60000});
  assert.equal(await page.getByLabel('本机项目目录').count(),0);
  assert.equal(await page.getByRole('button',{name:'打开目录',exact:true}).count(),0);
  assert.equal(await page.locator('.jiva-module').count(),6);
  assert.equal(await page.locator('.code-project-summary-line').count(),0);
  assert.equal(await page.locator('.jiva-demo [role=tab]').count(),0);
  await page.getByRole('button',{name:'查看本地存储',exact:true}).click();
  await page.locator('.jiva-module-notes h2').filter({hasText:'本地存储'}).waitFor();
  await page.getByRole('button',{name:'添加文字',exact:true}).click();
  assert.equal(await page.locator('.jiva-steps>button').count(),4);
  await page.getByRole('button',{name:'下一步',exact:true}).click();
  await page.locator('.jiva-module-notes h2').filter({hasText:'接住创建请求'}).waitFor();
  await page.locator('.jiva-source-link').click();
  await page.locator('.jiva-source .is-target').filter({hasText:'method === "POST"'}).waitFor();
  await page.getByRole('button',{name:'关闭源码',exact:true}).click();
  await page.getByRole('button',{name:'整个项目',exact:true}).click();
  await page.getByRole('button',{name:'脑图',exact:true}).click();
  await page.locator('.jiva-mind me-tpc').first().waitFor();
  await page.getByRole('button',{name:'源码目录',exact:true}).click();
  await page.locator('.jiva-tree-file').filter({hasText:/^server.js$/}).click();
  await page.locator('.jiva-source').filter({hasText:'createServer'}).waitFor();
  await page.getByRole('button',{name:'关闭源码',exact:true}).click();
  await page.getByRole('button',{name:'Git 变化',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Jiva · Git 变化',exact:true});
  await dialog.locator('.code-project-commit-row').first().waitFor();
  await dialog.getByLabel('搜索提交').fill('NO_SUCH_COMMIT_XYZ');assert.equal(await dialog.locator('.code-project-commit-row').count(),0);
  await dialog.getByLabel('搜索提交').fill('');await dialog.locator('.code-project-commit-row').first().click();
  await dialog.locator('.code-project-git-detail aside button').first().click();
  await dialog.locator('.code-project-diff').filter({hasText:/diff --git|没有文本差异/}).waitFor();
  await page.getByRole('button',{name:'关闭 Git 变化',exact:true}).click();
  await page.getByRole('button',{name:'整个项目',exact:true}).click();
  await page.getByRole('button',{name:'架构',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
});
