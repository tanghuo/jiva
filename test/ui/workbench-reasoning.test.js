import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createServer, chromium } from '../helpers/authenticatedServer.js';
import { resolveBrowserPath } from '../resolveBrowserPath.js';
import { stubWorkbenchModels } from '../helpers/workbenchModels.js';

const executablePath = resolveBrowserPath();
test('successive thoughts stay visible between tool groups, after completion and after reload', { timeout: 30000, skip: !executablePath }, async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'wiki-reasoning-ui-'));
  const stream = Promise.withResolvers(), next = Promise.withResolvers(), last = Promise.withResolvers(), finish = Promise.withResolvers();
  let app, browser;
  t.after(async () => {
    stream.resolve(); next.resolve(); last.resolve(); finish.resolve(); await browser?.close(); await app?.close();
    assert.equal(path.dirname(root), path.resolve(os.tmpdir())); assert.ok(path.basename(root).startsWith('wiki-reasoning-ui-'));
    await rm(root, { recursive: true, force: true, maxRetries: 3 });
  });
  app = await createServer({ port: 0, dataDir: root, agentWorkbenchEnabled: true, async openWorkbenchEngine(_settings, callbacks) {
    return { sessionId: 'thoughts', version: 'test', capabilities: {}, cancel() {}, async close() {}, async prompt(_text, delivery) {
      delivery('attempted');
      await callbacks.onEvent('reasoning.delta', { messageId: 'first', text: '先检查' });
      await stream.promise;
      await callbacks.onEvent('reasoning.delta', { messageId: 'first', text: '模型事件。' });
      await next.promise;
      await callbacks.onEvent('tool.updated', { id: 'read', title: '读取接入代码', status: 'completed' });
      await callbacks.onEvent('reasoning.delta', { messageId: 'second', kind: 'summary', partIndex: 0, text: '初步摘要' });
      await callbacks.onEvent('reasoning.updated', { messageId: 'second', kind: 'summary', partIndex: 0, text: '已核对摘要。' });
      await callbacks.onEvent('reasoning.updated', { messageId: 'second', kind: 'summary', partIndex: 0, text: '' });
      await last.promise;
      await callbacks.onEvent('tool.updated', { id: 'check', title: '验证界面展示', status: 'completed' });
      await callbacks.onEvent('reasoning.delta', { messageId: 'third', text: '最后确认内容完整保留。' });
      await finish.promise;
      await callbacks.onEvent('message.delta', { messageId: 'answer', phase: 'final_answer', text: '三个接入均已修复。' });
      return { stopReason: 'end_turn' };
    } };
  } });
  browser = await chromium.launch({ executablePath, headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.setDefaultTimeout(8000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await stubWorkbenchModels(page);
  await page.goto(app.url + '#workbench');
  await page.getByLabel('任务内容').fill('检查思考展示');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const thoughts = page.locator('.workbench-reasoning');
  async function expandThoughts() { await page.locator('.workbench-process-details').evaluateAll(elements => elements.forEach(element => { element.open = true; })); await thoughts.evaluateAll(elements => elements.forEach(element => { element.open = true; })); }
  await page.locator('.workbench-process-details > summary').waitFor();
  assert.equal(await page.locator('.workbench-process-details').evaluate(element => element.open), false);
  assert.equal(await thoughts.first().evaluate(element => element.open), false);
  await expandThoughts();
  await thoughts.first().locator('.workbench-markdown').getByText('先检查', { exact: true }).waitFor();
  await page.getByText('模型思考中', { exact: true }).waitFor();
  stream.resolve();
  await page.waitForFunction(() => document.querySelector('.workbench-reasoning .workbench-markdown')?.textContent === '先检查模型事件。');
  await thoughts.first().locator('.workbench-markdown').getByText('先检查模型事件。', { exact: true }).waitFor();
  await page.reload();
  await page.locator('.workbench-process-details > summary').waitFor();
  await expandThoughts();
  await thoughts.first().locator('.workbench-markdown').getByText('先检查模型事件。', { exact: true }).waitFor();
  next.resolve();
  await thoughts.nth(1).waitFor({ state: 'attached' });
  await expandThoughts();
  await thoughts.last().locator('.workbench-markdown').getByText('已核对摘要。', { exact: true }).waitFor();
  assert.equal(await thoughts.count(), 2);
  await thoughts.first().locator('.workbench-markdown').getByText('先检查模型事件。', { exact: true }).waitFor();
  assert.equal(await page.locator('.workbench-event.assistant').count(), 0);
  last.resolve();
  await thoughts.nth(2).waitFor({ state: 'attached' });
  await expandThoughts();
  await thoughts.last().locator('.workbench-markdown').getByText('最后确认内容完整保留。', { exact: true }).waitFor();
  await thoughts.nth(1).locator('.workbench-markdown').getByText('已核对摘要。', { exact: true }).waitFor();
  await thoughts.first().locator('.workbench-markdown').getByText('先检查模型事件。', { exact: true }).waitFor();
  assert.deepEqual(await page.locator('.workbench-turn .workbench-reasoning, .workbench-turn .workbench-execution').evaluateAll(elements => elements.map(element => element.className)), ['workbench-reasoning', 'workbench-execution', 'workbench-reasoning', 'workbench-execution', 'workbench-reasoning']);
  finish.resolve();
  await page.getByText('三个接入均已修复。', { exact: true }).waitFor();
  await page.locator('.workbench-turn-state[data-state="completed"]').waitFor({ state: 'attached' });
  const process = page.locator('.workbench-process');
  await process.waitFor();
  const toggle = process.locator('.workbench-process-toggle');
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  assert.match(await toggle.innerText(), /^用时 /);
  const rule = process.locator('.workbench-process-rule');
  assert.equal(await rule.isVisible(), true);
  assert.ok(await rule.evaluate(element => element.getBoundingClientRect().width > 200));
  assert.equal(await thoughts.first().locator('.workbench-markdown').getByText('先检查模型事件。', { exact: true }).isVisible(), false);
  await page.reload();
  await page.getByText('三个接入均已修复。', { exact: true }).waitFor();
  assert.equal(await page.locator('.workbench-process-toggle').getAttribute('aria-expanded'), 'false');
  assert.equal(await page.locator('.workbench-process-rule').isVisible(), true);
  assert.equal(await thoughts.first().locator('.workbench-markdown').getByText('先检查模型事件。', { exact: true }).isVisible(), false);
  await page.locator('.workbench-process-toggle').click();
  assert.equal(await thoughts.first().evaluate(element => element.open), false);
  await thoughts.first().locator('summary').click();
  await thoughts.nth(1).locator('summary').click();
  await thoughts.last().locator('summary').click();
  await thoughts.first().locator('.workbench-markdown').getByText('先检查模型事件。', { exact: true }).waitFor();
  await thoughts.nth(1).locator('.workbench-markdown').getByText('已核对摘要。', { exact: true }).waitFor();
  await thoughts.last().locator('.workbench-markdown').getByText('最后确认内容完整保留。', { exact: true }).waitFor();
  assert.equal(await thoughts.count(), 3);
  assert.equal(await page.locator('.workbench-reasoning summary').count(), 3);
  assert.equal(await page.locator('.workbench-execution').count(), 2);
  for (const group of await page.locator('.workbench-execution').all()) assert.equal(await group.evaluate(element => element.open), false);
  assert.equal(await page.getByText('初步摘要', { exact: true }).count(), 0);
  assert.equal(await page.locator('.workbench-event.assistant').innerText(), '三个接入均已修复。');
  assert.ok(await thoughts.first().evaluate(element => parseFloat(getComputedStyle(element).fontSize)) < await page.locator('.workbench-event.assistant').evaluate(element => parseFloat(getComputedStyle(element).fontSize)));
  await mkdir('.local/workbench-ui', { recursive: true });
  await page.screenshot({ path: '.local/workbench-ui/reasoning-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await thoughts.first().locator('.workbench-markdown').getByText('先检查模型事件。', { exact: true }).waitFor();
  await thoughts.nth(1).locator('.workbench-markdown').getByText('已核对摘要。', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: '.local/workbench-ui/reasoning-mobile.png' });
  assert.deepEqual(errors, []);
});
